<?php

namespace App\Services\HomeDoctor;

class Safety
{
    public static function referral(string $text): ?array
    {
        $text = preg_replace('/[\x{064B}-\x{065F}\x{200C}\x{200D}]/u', ' ', strtr($text, ['ك' => 'ک', 'ي' => 'ی', 'ى' => 'ی']));
        $text = preg_replace('/[\s\p{P}]+/u', ' ', $text);

        $risk = [
            'gas' => '/بوی\s*(?:شدید\s*)?گاز|بو\s*ی\s*گاز|نشت\s*گاز|صدای\s*هیس\s*گاز|مونو\s*اکسید\s*کربن|گاز\s*گرفتگی|گاز\s*نشت/u',
            'electric' => '/جرقه|برق\s*گرفتگی|سیم\s*لخت|بوی\s*سوختگی|دود.*(?:پریز|سیم|تابلو\s*برق)|(?:پریز|سیم|تابلو\s*برق).*دود|آب.*(?:روی|کنار|داخل)\s*(?:پریز|تابلو\s*برق)/u',
            'fire' => '/آتش\s*سوزی|آتش\s*گرفته|شعله\s*ور|دود\s*غلیظ/u',
            'structure' => '/ریزش\s*(?:دیوار|سقف|ساختمان|تیر)|سقف.*(?:شکم\s*داده|افتاده|ریخته)|فروریخت|فرو\s*ریخت|احتمال\s*(?:ریزش|سقوط)|ستون.*(?:شکسته|خم\s*شده)|ترک.*(?:به\s*سرعت|سریع|ناگهانی).*بزرگ/u',
        ];
        $matches = array_filter($risk, static function ($pattern) use ($text) {
            return preg_match($pattern, $text) === 1;
        });
        if (!$matches) {
            return null;
        }

        return self::urgent(array_key_first($matches));
    }

    public static function urgent(string $risk): array
    {
        $instructions = [
            'gas' => [
                'احتمال خطر نشت گاز یا مسمومیت وجود دارد.',
                'از محل خارج شوید. در محل از کلید برق، جرقه یا شعله استفاده نکنید. از جای امن با امداد گاز یا آتش‌نشانی تماس بگیرید.',
                'امداد گاز یا آتش‌نشانی',
            ],
            'electric' => [
                'احتمال خطر برق‌گرفتگی یا آتش‌سوزی وجود دارد.',
                'از سیم، وسیله و آب اطراف آن فاصله بگیرید. به تجهیزات دست نزنید و از جای امن با آتش‌نشانی یا متخصص برق تماس بگیرید.',
                'آتش‌نشانی یا برق‌کار دارای صلاحیت',
            ],
            'fire' => [
                'نشانه‌های آتش‌سوزی یا دود نیازمند رسیدگی فوری است.',
                'به محل دود یا شعله نزدیک نشوید. اگر خروج ایمن است از ساختمان خارج شوید و از جای امن با آتش‌نشانی تماس بگیرید.',
                'آتش‌نشانی',
            ],
            'structure' => [
                'احتمال ناپایداری سازه وجود دارد.',
                'از بخش آسیب‌دیده دور شوید. اگر خروج ایمن است از ساختمان خارج شوید و بازدید فوری امداد یا مهندس سازه را درخواست کنید.',
                'آتش‌نشانی یا مهندس سازه',
            ],
        ];
        [$summary, $action, $specialist] = $instructions[$risk] ?? [
            'نشانهٔ گزارش‌شده به بررسی فوری نیاز دارد.',
            'از محل خطر دور شوید و از جای امن با مرکز امداد یا متخصص دارای صلاحیت تماس بگیرید.',
            'امداد یا متخصص دارای صلاحیت',
        ];

        return [
            'summary' => $summary, 'urgency' => 'urgent', 'confidence' => 'unknown',
            'observations' => [], 'possible_causes' => [], 'next_steps' => [$action],
            'specialist' => $specialist, 'source' => 'safety_rule',
        ];
    }
}
