    public static function categories(): array
    {
        $categories = self::defaults();
        foreach (DB::table('spad_home_doctor_category_overrides')->get() as $override) {
            if (!isset($categories[$override->code])) {
                continue;
            }
            foreach (['label', 'description', 'guide'] as $field) {
                if ($override->{$field} !== null) {
                    $categories[$override->code][$field] = $override->{$field};
                }
            }
            $categories[$override->code]['enabled'] = (bool) $override->enabled;
        }
        return $categories;
    }

    public static function enabled(): array
    {
        return array_filter(self::categories(), static function ($category) {
            return $category['enabled'];
        });
    }

